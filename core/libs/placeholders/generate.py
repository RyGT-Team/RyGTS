"""FEAT-GTS-261: writes a placeholder library's C source and module definition from its export list.

  python generate.py <list.nids> <output.c> <output.def>

Each line of the list is "<library> <NID>": a function GT Sport imports that RyGTS does not implement.
The library exports one function per NID that reports "[stub] <library> <NID>" on its first call and
returns 0. A library with an empty list exports only ryty_stub_none: the game loads it at start but
calls nothing in it. See README.md.
"""
import re
import sys
from pathlib import Path

ENTRY = re.compile(r'^(lib[A-Za-z0-9_\-]+) ([A-Za-z0-9+\-]{11})$')


def main(listing, source, definition):
    library = Path(listing).stem
    entries = []
    for number, line in enumerate(Path(listing).read_text(encoding='ascii').splitlines(), 1):
        match = ENTRY.match(line)
        if not match:
            sys.exit(f'{listing}:{number}: expected "<library> <NID>"')
        entries.append(match.groups())
    nids = [nid for _, nid in entries]
    if len(set(nids)) != len(nids):
        sys.exit(f'{listing}: a NID is listed twice')
    lines = ['/* Generated by core/libs/placeholders/generate.py from ' + library + '.nids; do not edit. */',
             '#include <stdint.h>', '#include <stdio.h>', '#include <windows.h>', '']
    if entries:
        lines.append(f'static volatile LONG seen[{len(entries)}];')
        lines.append('static const char* const names[] = {' +
                     ','.join('"' + owner + ' ' + nid + '"' for owner, nid in entries) + '};')
        lines.append('static void note(int i) { if (!InterlockedExchange(&seen[i], 1)) { fputs("[stub] ", stderr); '
                     'fputs(names[i], stderr); fputc(10, stderr); fflush(stderr); } }')
        for i in range(len(entries)):
            lines.append(f'__attribute__((sysv_abi)) int64_t s{i}(void) {{ note({i}); return (int32_t)0; }}')
    else:
        lines.append('__attribute__((sysv_abi)) int64_t ryty_stub_none(void) { return 0; }')
    Path(source).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    exports = [f'  "{nid}"=s{i}' for i, (_, nid) in enumerate(entries)] or ['  ryty_stub_none']
    Path(definition).write_text('\n'.join([f'LIBRARY {library}.prx', 'EXPORTS'] + exports) + '\n',
                                encoding='ascii', newline='\n')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
